#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ContactInfo {
    pub email: String,
    pub phone: String,
    pub location: String,
    pub website: String,
    pub linkedin: String,
    pub github: String,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct WorkEntry {
    pub role: String,
    pub company: String,
    pub location: String,
    pub start: String,
    pub end: String,
    pub description: String,
    pub highlights: Vec<String>,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Skills {
    pub technical: Vec<String>,
    pub tools: Vec<String>,
    pub other: Vec<String>,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct EducationEntry {
    pub degree: String,
    pub institution: String,
    pub location: String,
    pub year: String,
    pub details: String,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
